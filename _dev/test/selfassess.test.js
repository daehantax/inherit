const {open,expect}=require('./harness');
const F='상속세과세표준 자진납부.html';
(async()=>{
  console.log(F);
  // 1. ⑰ 20억, ⑱ 10억, 부동산 감정평가 800만 → ⑲ 500만 → ⑳ 9.95억 → 30%−6천만 = 238,500,000
  //    신고세액공제 3% = 7,155,000 → ㊱ = ㊵ = ㊹ = 231,345,000
  let p=await open(F);
  p.set('v17',2e9); p.set('v18',1e9); p.set('feeRE',8e6);
  expect('⑲ 감정평가수수료 500만 한도', p.num('v19'), 5e6);
  expect('⑳ 과세표준 9.95억', p.num('v20'), 995000000);
  expect('㉒ 산출세액', p.num('v22'), 238500000);
  expect('㉝ 신고세액공제 3%', p.num('v33'), 7155000);
  expect('㊱ 공제 후 납부할 세액', p.num('v36'), 231345000);
  expect('㊹ 신고납부세액', p.num('v44'), 231345000);
  // 비상장주식 평가수수료 1,500만 → 1천만 한도 → ⑲ 1,500만
  p.set('feeStock',1.5e7);
  expect('⑲ 부동산 500만 + 비상장 1천만', p.num('v19'), 1.5e7);

  // 2. 세대생략: 손자 5억 / 총 20억 → 25% × 30% → 238,500,000 × .075 = 17,887,500 ; ㉔ 256,387,500 ; 신고공제 floor(×3%) = 7,691,625 ; ㊱ 248,695,875
  p=await open(F);
  p.set('v17',2e9); p.set('v18',1e9); p.set('feeRE',8e6); p.set('skipValue',5e8); p.set('totalValue',2e9);
  expect('㉓ 세대생략 가산 30%', p.num('v23'), 17887500);
  expect('㉔ 총산출세액', p.num('v24'), 256387500);
  expect('㉝ 신고공제(가산 포함 기준)', p.num('v33'), 7691625);
  expect('㊱', p.num('v36'), 248695875);
  // 미성년자 & 25억(20억 초과) / 50억 → 50% × 40% → 238,500,000 × .2 = 47,700,000
  p.set('skipValue',2.5e9); p.set('totalValue',5e9); p.check('skipMinor',true);
  expect('㉓ 미성년자 20억 초과 → 40%', p.num('v23'), 47700000);

  // 3. 과세최저한: ⑰ 5억 40만, ⑱ 5억 → ⑳ 40만 < 50만 → 0
  p=await open(F);
  p.set('v17',500400000); p.set('v18',5e8);
  expect('과세최저한 → ⑳ 0', p.num('v20'), 0);
  expect('㉒ 0', p.num('v22'), 0);

  // 4. 분납 한도: ⑳ 1억 → ㉒ 1천만, 기한후(공제 0), ㊳ 500만 → ㊵ 1,500만 → 분납 한도 500만 ; 입력 800만 → 500만 → ㊹ 1,000만
  p=await open(F);
  p.set('v17',1e8); p.radio('filing','late'); p.set('v38',5e6); p.set('v43',8e6);
  expect('㊵ 납부할 세액 1,500만', p.num('v40'), 1.5e7);
  expect('㊹ 분납 한도 500만 적용 → 1,000만', p.num('v44'), 1e7);
  // 연부연납은 2천만 이하라 불가 → 0
  p.set('v43',0); p.set('v41',5e6);
  expect('2천만 이하 연부연납 불가 → ㊹ 그대로 1,500만', p.num('v44'), 1.5e7);

  // 5. 연부연납 + 분납 동시 → 분납 무시: ⑳ 10억 → 2.4억, 공제 720만 → ㊵ 232,800,000 ; 연부연납 2억, 분납 1천만(무시) → ㊹ 32,800,000
  p=await open(F);
  p.set('v17',1e9); p.set('v41',2e8); p.set('v43',1e7);
  expect('㊵ 232,800,000', p.num('v40'), 232800000);
  expect('연부연납+분납 동시 → 분납 0 → ㊹ 32,800,000', p.num('v44'), 32800000);
  // 2천만 초과 분납 한도 50%: 연부연납 0, 분납 2억 → 한도 116,400,000 → ㊹ 116,400,000
  p.set('v41',0); p.set('v43',2e8);
  expect('분납 50% 한도 → ㊹ 116,400,000', p.num('v44'), 116400000);

  // 6. 세액공제: ⑳ 10억 → 2.4억 ; ㉙ 1천만, ㉛ 200만, ㉞ 100만 → 공제기준 2.27억 × 3% = 6,810,000 ; ㉗ 19,810,000 ; ㊱ 220,190,000
  p=await open(F);
  p.set('v17',1e9); p.set('v29',1e7); p.set('v31',2e6); p.set('v34',1e6);
  expect('㉘ 증여세액공제 소계', p.num('v28'), 1e7);
  expect('㉝ 신고공제 (공제 차감 후 3%)', p.num('v33'), 6810000);
  expect('㉗ 세액공제 합계', p.num('v27'), 19810000);
  expect('㊱', p.num('v36'), 220190000);
  console.log(p.errors.length?('JS errors: '+p.errors):'  (JS 오류 없음)');
})();
