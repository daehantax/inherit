const {open,expect,near}=require('./harness');
(async()=>{
  console.log('상속으로인한재산세.html');
  // 감사 사례 1: 종전 5억 1주택 + 상속 3억 (5년 이내 → 주택수 제외)
  //  종전 5억: 1세대1주택 44% → 과표 2.2억, 공시가 9억 이하 특례세율 → 12만 + 0.7억×0.2% = 26만 ; 도시 2.2억×0.14% = 30.8만 ; 교육 5.2만
  //  상속 3억: 60% → 1.8억, 표준 → 19.5만 + 0.3억×0.25% = 27만 ; 도시 25.2만 ; 교육 5.4만
  //  합: 재산세 53만, 도시 56만, 교육 10.6만 ; 종부세: 8억 < 12억 → 0
  let p=await open('상속으로인한재산세.html');
  p.set('h1',5e8); p.set('ihValue',3e8);
  expect('상속 전 재산세(5억 특례) 26만', p.num('r_pb_tax'), 260000);
  expect('상속 후 재산세 합 53만', p.num('r_pa_tax'), 530000);
  expect('상속 후 도시지역분 56만', p.num('r_pa_city'), 560000);
  expect('상속 후 지방교육세 10.6만', p.num('r_pa_edu'), 106000);
  expect('상속 후 종부세 0 (8억<12억)', p.num('r_ca_all'), 0);
  expect('상속 후 공제용 주택수 1', p.text('r_ca_n'), '1주택');

  // 감사 사례 2: 1주택 8억 → 종부세 0 ; 재산세 45% → 3.6억 과표, 특례 → 42만 + 0.6억×0.35% = 63만
  p=await open('상속으로인한재산세.html');
  p.set('h1',8e8);
  expect('1주택 8억 종부세 0', p.num('r_cb_all'), 0);
  expect('1주택 8억 재산세 63만', p.num('r_pb_tax'), 630000);

  // 감사 사례 3: 1주택 15억, 70세, 15년 (상속 없음)
  //  재산세: 45% → 6.75억, 9억 초과 → 표준: 57만 + 3.75억×0.4% = 207만
  //  종부세: (15−12)×0.6 = 1.8억 → 0.5% = 90만
  //  재산세공제(시행령 §4의3) = 207만 × (1.8억×45%×0.4%) ÷ 표준세율 재산세 207만 = 324,000 ; 산출 576,000
  //  세액공제 40%+50% → 80% 한도 → 460,800 ; 납부 115,200 ; 농특세 23,040 ; 합 138,240
  p=await open('상속으로인한재산세.html');
  p.set('h1',1.5e9); p.set('age',70); p.set('hold',15);
  expect('15억 재산세 207만', p.num('r_pb_tax'), 2070000);
  expect('종부세액 90만', p.num('r_cb_tax'), 900000);
  expect('공제 재산세 324,000', p.num('r_cb_prop'), 324000);
  expect('산출세액 576,000', p.num('r_cb_calc'), 576000);
  expect('세액공제 80% = 460,800', p.num('r_cb_credit'), 460800);
  expect('납부 115,200', p.num('r_cb_pay'), 115200);
  expect('종부세 총부담(농특세 포함) 138,240', p.num('r_cb_all'), 138240);

  // 사례 4: 위 15억 1주택 + 상속 5억 (5년 이내) → 합 20억, 1세대1주택 유지(12억 공제)
  //  과표 (20−12)×0.6 = 4.8억 → 0.7% − 60만 = 276만
  //  재산세: 15억 207만(과표 6.75억) + 상속 5억 60% → 3억 과표 표준 → 19.5만+1.5억×0.25% = 57만 → 합 264만, 과표합 9.75억
  //  공제 재산세 = 264만 × (4.8억 × 실효 공정시장가액비율 9.75/20 × 0.4% = 936,000)
  //               ÷ 합산 과표 9.75억의 표준세율 재산세(57만 + 6.75억×0.4% = 327만) = 755,669
  //  산출 = 2,760,000 − 755,669 = 2,004,331 ; 세액공제 = 산출 × (15/20) × 80% = 1,202,598 ; 납부 801,733
  p.set('ihValue',5e8);
  expect('합산 20억 공제 12억 → 과표 4.8억', p.num('r_ca_base'), 4.8e8);
  expect('종부세액 276만', p.num('r_ca_tax'), 2760000);
  expect('공제 재산세 755,669', p.num('r_ca_prop'), 755669);
  expect('세액공제(1주택분 75%×80%) 1,202,598', p.num('r_ca_credit'), 1202598);
  expect('납부 801,733', p.num('r_ca_pay'), 801733);
  expect('상속 후 재산세 합 264만', p.num('r_pa_tax'), 2640000);

  // 사례 5: 3주택(각 10억) + 상속 10억, 5년 경과(2015-01-01), 지분 100%, 수도권 → 4주택 중과
  //  상속 전: 합 30억−9억 = 21억×0.6 = 12.6억 > 12억 & 3주택 → 중과: 12.6억×2% − 1440만 = 1,080만
  //   재산세 각 60% → 6억 과표, 표준 57만+3억×0.4% = 177만 ×3 = 531만 ; 합산 과표 18억 표준세율 재산세 = 57만+15억×0.4% = 657만
  //   공제 = 531만 × (12.6억×60%×0.4% = 3,024,000) ÷ 657만 = 2,444,054 → 산출 8,355,946
  //  상속 후: 합 40억−9억 = 31억×0.6 = 18.6억 → 18.6억×2% − 1440만 = 2,280만 ; 재산세 708만, 합산 과표 24억 → 897만
  //   공제 = 708만 × 4,464,000 ÷ 897만 = 3,523,424 → 산출 19,276,576
  p=await open('상속으로인한재산세.html');
  p.set('h1',1e9); p.set('h2',1e9); p.set('h3',1e9); p.set('ihValue',1e9); p.set('ihDate','2015-01-01');
  expect('상속 전 3주택 중과 종부세액 1,080만', p.num('r_cb_tax'), 10800000);
  expect('상속 전 산출 8,355,946', p.num('r_cb_calc'), 8355946);
  expect('상속 후 주택수 4', p.text('r_ca_n'), '4주택');
  expect('상속 후 종부세액 2,280만', p.num('r_ca_tax'), 22800000);
  expect('상속 후 산출 19,276,576', p.num('r_ca_calc'), 19276576);
  // 지분 30% 로 바꾸면 소수지분 → 주택수 제외 → 3주택 ; 합 33억 → (33−9)×0.6 = 14.4억 → 14.4억×2%−1440만 = 1,440만
  p.set('ihShare',30);
  expect('소수지분 → 3주택', p.text('r_ca_n'), '3주택');
  expect('소수지분 종부세액 1,440만', p.num('r_ca_tax'), 14400000);

  // 사례 6: 무주택 + 상속 4억 → 상속주택이 1세대1주택: 44% → 1.76억 과표 특례 → 12만 + 0.26억×0.2% = 17.2만
  p=await open('상속으로인한재산세.html');
  p.set('ihValue',4e8);
  expect('무주택 상속 4억 재산세 17.2만', p.num('r_pa_tax'), 172000);
  expect('무주택 상속 → 1주택', p.text('r_ca_n'), '1주택');
  console.log(p.errors.length?('JS errors: '+p.errors):'  (JS 오류 없음)');
})();
// 교차 검증: 같은 15억 1주택(70세·15년) 종부세가 절세보고서와 이 페이지에서 같아야 한다 (재산세 공제 공통 산식)
(async()=>{
  const a=await open('상속으로인한재산세.html'); a.set('h1',1.5e9); a.set('age',70); a.set('hold',15);
  const g=await open('inheritGold.html'); g.set('owned_houses',1); g.set('gongsi_1',1.5e9); g.set('gongsi_2',0); g.set('age',70); g.set('period',15); g.click('#btnCompTax');
  expect('교차: 공제 재산세 (보고서 = 재산세 페이지)', g.num('ct1_deductible_property_tax'), a.num('r_cb_prop'));
  expect('교차: 종부세 납부 (보고서 10원 절사 = 재산세 페이지)', g.num('ct1_payable_tax'), Math.floor(a.num('r_cb_pay')/10)*10);
})();
